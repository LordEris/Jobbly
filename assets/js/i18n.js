export function lang() {
  return document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'fr'
}

/** Le texte d'une clé, {variables} remplacées ; la clé elle-même si absente. */
export function t(key, vars) {
  const dict = STRINGS[lang()]
  let s = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : STRINGS.fr[key]
  if (typeof s !== 'string') return key
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m))
  return s
}

/**
 * Réécrit les textes posés dans le balisage : `data-i18n` (texte),
 * `data-i18n-attr="aria-label:clé;placeholder:clé"` (attributs).
 */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.getAttribute('data-i18n')) })
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.getAttribute('data-i18n-attr').split(';')) {
      const [attr, key] = pair.split(':')
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()))
    }
  })
}
